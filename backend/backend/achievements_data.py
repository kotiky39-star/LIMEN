def mock_unlocked(steam_username: str, game_id: str, index: int, rarity: float) -> bool:
    """
    Детерминированная имитация прогресса Steam: одно и то же имя всегда даёт один и тот же набор.
    Чем выше процент получения достижения, тем выше шанс, что оно «открыто».
    Та же формула (FNV-1a 32 bit) реализована во фронтенде для демо-режима без сервера.
    """
    h = 0x811C9DC5
    for byte in f"{steam_username.lower()}:{game_id}:{index}".encode("utf-8"):
        h ^= byte
        h = (h * 0x01000193) & 0xFFFFFFFF
    return (h % 100) < rarity
